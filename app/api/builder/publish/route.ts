import { NextResponse } from 'next/server';

import {
  commitFiles,
  GitHubError,
  isEditableFile,
  UPLOAD_DIR,
  type FileChange,
} from '@/lib/builder/github';
import { serialise } from '@/lib/builder/paths';
import { guardRequest } from '@/lib/builder/session';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';

type PublishBody = {
  /** Content files that changed, as parsed JSON. */
  files?: Record<string, unknown>;
  /** Newly uploaded photographs, staged by the editor until publish. */
  images?: { path: string; base64: string }[];
  message?: string;
};

const MAX_IMAGE_BYTES = 3 * 1024 * 1024;

/**
 * Publishes an edit.
 *
 * Content and any new photography land in a single commit, so the site never
 * deploys a state where the text refers to an image that is not there yet.
 */
export async function POST(request: Request) {
  const denied = await guardRequest();
  if (denied) return denied;

  let body: PublishBody;
  try {
    body = (await request.json()) as PublishBody;
  } catch {
    return NextResponse.json({ error: 'Pedido inválido.' }, { status: 400 });
  }

  const changes: FileChange[] = [];

  for (const [path, document] of Object.entries(body.files ?? {})) {
    if (!isEditableFile(path)) {
      return NextResponse.json({ error: `Ficheiro não editável: ${path}` }, { status: 400 });
    }
    changes.push({ path, content: serialise(document) });
  }

  for (const image of body.images ?? []) {
    // Paths are generated by the upload route, but this is the boundary where
    // a crafted request would arrive, so the constraint is enforced again.
    if (!image.path.startsWith(`${UPLOAD_DIR}/`) || image.path.includes('..')) {
      return NextResponse.json(
        { error: `Caminho de imagem inválido: ${image.path}` },
        { status: 400 },
      );
    }
    if (Buffer.byteLength(image.base64, 'base64') > MAX_IMAGE_BYTES) {
      return NextResponse.json({ error: 'Imagem demasiado grande.' }, { status: 413 });
    }
    changes.push({ path: image.path, content: image.base64, encoding: 'base64' });
  }

  if (changes.length === 0) {
    return NextResponse.json({ error: 'Não há alterações para publicar.' }, { status: 400 });
  }

  const summary = (body.message ?? '').trim().slice(0, 72) || 'Actualizar conteúdo';
  const message = `${summary}\n\nEditado no construtor Ophelia.`;

  try {
    const commit = await commitFiles(changes, message);
    return NextResponse.json({ ok: true, ...commit });
  } catch (error) {
    if (error instanceof GitHubError) {
      const status = error.code === 'conflict' ? 409 : error.code === 'auth' ? 502 : 502;
      return NextResponse.json({ error: error.message, code: error.code }, { status });
    }
    console.error('[publish] unexpected failure:', error);
    return NextResponse.json({ error: 'Não foi possível publicar.' }, { status: 500 });
  }
}
